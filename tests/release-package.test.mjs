import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, realpathSync, mkdirSync, readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createRelease } from '../scripts/package-release.mjs';
import { verifyRelease } from '../scripts/verify-release.mjs';

test('交付包只包含源码、拒绝泄密/覆盖/篡改、校验完整性',t=>{
  const parent=realpathSync(tmpdir()),folder=mkdtempSync(path.join(parent,'delta-release-')),root=path.join(folder,'source'),target=path.join(folder,'release');
  t.after(()=>{const resolved=realpathSync(folder);assert.equal(path.dirname(resolved),parent);assert.ok(path.basename(resolved).startsWith('delta-release-'));rmSync(resolved,{recursive:true});});
  for(const dir of ['dist','server','scripts','tests','config','deploy','db','docs','.local','node_modules','archive'])mkdirSync(path.join(root,dir),{recursive:true});
  writeFileSync(path.join(root,'package-lock.json'),JSON.stringify({packages:{'':{},'node_modules/better-auth':{version:'1.7.6',license:'MIT'}}}));
  writeFileSync(path.join(root,'dist','index.html'),'<h1>网站</h1>');writeFileSync(path.join(root,'docs','current.md'),'当前说明');
  writeFileSync(path.join(root,'.local','auth-secret'),'do-not-share');writeFileSync(path.join(root,'archive','old.txt'),'old-framework');
  writeFileSync(path.join(root,'config','staging.env.example'),'BETTER_AUTH_SECRET=\nSTAGING_ACCESS_TOKEN=\n');
  writeFileSync(path.join(root,'config','channels.env.example'),'LOGIN_CHANNEL_MODE=disabled\nSMS_SECRET_FILE=\nWECHAT_LOGIN_SECRET_FILE=\nQQ_LOGIN_SECRET_FILE=\nPAYMENT_SECRET_FILE=\n');
  mkdirSync(path.join(root,'docs','release-checks','stage69'),{recursive:true});
  writeFileSync(path.join(root,'docs','release-checks','stage69','evidence.zip'),'private-evidence');
  writeFileSync(path.join(root,'docs','release-checks','stage69','browser.txt'),'private-evidence');
  mkdirSync(path.join(root,'.github','workflows'),{recursive:true});
  writeFileSync(path.join(root,'.github','workflows','quality.yml'),'name: checks\n');
  writeFileSync(path.join(root,'.github','private-notes.txt'),'not-a-release-file');
  assert.equal(createRelease(target,{root}).ok,true);assert.equal(existsSync(path.join(target,'.local')),false);assert.equal(existsSync(path.join(target,'archive')),false);
  assert.ok(!readFileSync(path.join(target,'RELEASE_MANIFEST.json'),'utf8').includes('do-not-share'));assert.equal(verifyRelease(target).ok,true);
  assert.equal(readFileSync(path.join(target,'.github','workflows','quality.yml'),'utf8'),'name: checks\n');
  assert.equal(existsSync(path.join(target,'.github','private-notes.txt')),false);
  assert.equal(existsSync(path.join(target,'docs','release-checks')),false);
  assert.equal(readFileSync(path.join(target,'config','channels.env.example'),'utf8').includes('SMS_SECRET_FILE='),true);
  writeFileSync(path.join(root,'config','channels.env.example'),'SMS_SECRET_FILE=/private/credential\n');
  assert.throws(()=>createRelease(path.join(folder,'private-channel'),{root}));
  assert.equal(existsSync(path.join(folder,'private-channel')),false);
  writeFileSync(path.join(root,'config','channels.env.example'),'SMS_SECRET_FILE=\n');
  assert.throws(()=>createRelease(target,{root}));assert.throws(()=>createRelease(path.join(root,'nested'),{root}));
  writeFileSync(path.join(target,'dist','index.html'),'changed');assert.equal(verifyRelease(target).problems[0].code,'HASH_MISMATCH');
  writeFileSync(path.join(target,'extra.txt'),'extra');assert.ok(verifyRelease(target).problems.some(p=>p.code==='UNEXPECTED_FILE'));
  writeFileSync(path.join(root,'config','staging.env.example'),'BETTER_AUTH_SECRET=should-not-export\n');assert.throws(()=>createRelease(path.join(folder,'secret'),{root}));assert.equal(existsSync(path.join(folder,'secret')),false);
  writeFileSync(path.join(root,'config','staging.env.example'),'BETTER_AUTH_SECRET=\n');
  writeFileSync(path.join(root,'config','private.env'),'private');assert.throws(()=>createRelease(path.join(folder,'private-env'),{root}));
});
